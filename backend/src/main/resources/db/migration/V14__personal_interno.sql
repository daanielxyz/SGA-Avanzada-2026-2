-- Personal interno (DEC-71). Un usuario nace sin contraseña: la fija él con el código de activación que le llega al
-- correo. Cambiar o restablecer la contraseña sube la versión de sus sesiones: los tokens con la anterior dejan de
-- valer.
ALTER TABLE usuario ALTER COLUMN contrasena DROP NOT NULL;
ALTER TABLE usuario ADD COLUMN version_sesiones INTEGER DEFAULT 0 NOT NULL;

-- Códigos de un solo uso del personal: activación (24 horas) y recuperación de la contraseña (15 minutos, USU-06).
CREATE TABLE codigo_usuario (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  VARCHAR(40)  NOT NULL,
    proposito   VARCHAR(20)  NOT NULL,
    pin_cifrado VARCHAR(100) NOT NULL,                                          -- resumen BCrypt
    creado_en   TIMESTAMP    NOT NULL,
    expira_en   TIMESTAMP    NOT NULL,
    intentos    INT          NOT NULL DEFAULT 0,
    usado       BOOLEAN      NOT NULL DEFAULT FALSE,
    CHECK (proposito IN ('ACTIVACION', 'RECUPERACION')),
    CHECK (intentos BETWEEN 0 AND 5)
);

CREATE INDEX ix_codigo_usuario ON codigo_usuario (usuario_id, proposito, creado_en);

-- Tokens cerrados antes de vencer (CU-48). Se guardan hasta su vencimiento; después ya no valen de todos modos.
CREATE TABLE token_revocado (
    jti       VARCHAR(64)              PRIMARY KEY,
    expira_en TIMESTAMP WITH TIME ZONE NOT NULL
);
