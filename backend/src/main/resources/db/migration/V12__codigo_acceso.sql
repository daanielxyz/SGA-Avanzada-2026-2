-- PIN de un solo uso del huésped (DEC-68 · DEC-69): para iniciar sesión (llega al correo) y para cambiar el correo
-- de su cuenta (llega al teléfono y al correo actual). Vive fuera del dominio, como la tabla usuario: el titular
-- es la cuenta y aquí solo se guarda el PIN, nunca en claro.
CREATE TABLE codigo_acceso (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titular_id   VARCHAR(40)  NOT NULL,                                         -- sin FK: es de seguridad (USU-07)
    proposito    VARCHAR(20)  NOT NULL,
    pin_cifrado  VARCHAR(100) NOT NULL,                                         -- resumen BCrypt
    nuevo_correo VARCHAR(150),                                                  -- solo en un cambio de correo
    creado_en    TIMESTAMP    NOT NULL,
    expira_en    TIMESTAMP    NOT NULL,                                         -- 15 minutos después
    intentos     INT          NOT NULL DEFAULT 0,                               -- se bloquea al quinto fallo
    usado        BOOLEAN      NOT NULL DEFAULT FALSE,                           -- un solo uso
    CHECK (proposito IN ('INICIO_SESION', 'CAMBIO_CORREO')),
    CHECK (intentos BETWEEN 0 AND 5)
);

-- El PIN vigente de un titular es el último que se le emitió para ese propósito.
CREATE INDEX ix_codigo_acceso_titular ON codigo_acceso (titular_id, proposito, creado_en);

-- El huésped entra con su correo (DEC-68) y ve sus reservas, de la más reciente a la más antigua (USU-04).
CREATE INDEX ix_titular_correo ON titular (alojamiento_id, correo);
CREATE INDEX ix_reserva_titular ON reserva (titular_id, creada_en);
